export function imageFor(row, kind = 'parts') {
  if (/^upload-[a-f0-9]{32}$/.test(row.image_key || '')) return `/api/media/images/${row.image_key}`
  return images[row.image_key]?.src || `data:image/svg+xml,${encodeURIComponent('<svg xmlns="http://www.w3.org/2000/svg" width="240" height="160"><rect width="240" height="160" fill="#f5f5f7"/><path d="M104 48h32v32h-32z" fill="none" stroke="#c0c3cb" stroke-width="2"/><text x="120" y="110" text-anchor="middle" fill="#969aa4" font-size="12" font-family="sans-serif">暂无图片</text></svg>')}`
}
export function imageOptions(kind) {
  const prefix = { parts: 'part-', warehouses: 'warehouse-', suppliers: 'supplier-' }[kind]
  return Object.entries(images).filter(([key]) => key.startsWith(prefix))
}
